"""Generate content/core/rnd/estimate_points.ron: the committed 256 x 3 normal-transformed scrambled Sobol set
for estimate() (spec §4.5.7, S-1). Columns: z_G, z_S (correlated in growth()), z_cost."""
import pathlib
from scipy.special import ndtri
from scipy.stats import qmc

SEED = 0   # the set the prototype tests over 20 seeds use seed 0..19; seed 0 is committed

if __name__ == "__main__":
    z = ndtri(qmc.Sobol(3, scramble=True, seed=SEED).random(256))
    rows = ",\n".join("    (%.17g, %.17g, %.17g)" % tuple(r) for r in z)
    out = pathlib.Path(__file__).resolve().parents[2] / "content/core/rnd/estimate_points.ron"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by prototypes/rnd/make_estimate_points.py (WS-05 §4.5.7). Do not edit.\n[\n" + rows + ",\n]\n")
    print("wrote", out)
